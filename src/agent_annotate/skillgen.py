"""Write a provider's skill directory from the packaged skill text.

The package is canonical; a skill directory (``~/.claude/skills/annotate``,
a skills-org checkout, ``~/.agents/skills/annotate``) is a deployment of it
and holds no code. ``annotate install-skill --provider claude --dest DIR``
writes into DIR:

    SKILL.md                    the shared provider skill text, copied verbatim
    references/*.md             the one set of references, copied verbatim
    hooks/check-comment-bus.sh  a shim that execs the packaged hook, so a
                                settings.json entry pointing into the skill
                                directory keeps working
    agents/openai.yaml          Codex only

Every write is atomic and happens only when the content differs. Obsolete
manifest-owned files are removed only when their hashes still match.
The function returns one line per file
saying what happened, so a second run prints "unchanged" for everything.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shlex
import sys
from pathlib import Path

from .paths import CONFIG_DIR, HOOK_SCRIPT, PACKAGE_DIR, SESSION_START_SCRIPT

SKILLS_DIR = PACKAGE_DIR / "skills"
PROVIDERS = ("claude", "codex")

GENERATED_MARK = "generated by `annotate install-skill`"

_FRONTMATTER_RE = re.compile(r"\A---\n.*?\n---\n", re.DOTALL)


def skill_source(provider: str) -> Path:
    if provider not in PROVIDERS:
        raise ValueError(f"unknown provider {provider!r}; expected one of {', '.join(PROVIDERS)}")
    return SKILLS_DIR / provider


def render_skill_md(provider: str, text: str) -> str:
    """Deploy the canonical text verbatim for every provider and plugin."""
    skill_source(provider)
    if not _FRONTMATTER_RE.match(text):
        raise ValueError("SKILL.md must start with front matter")
    return text


def hook_shim(python: str | None = None) -> str:
    """A check-comment-bus.sh that runs the packaged hook of THIS install.

    The packaged script is preferred (it locates its Python next to itself and
    never consults `annotate` on PATH, which may be libgd). The interpreter
    that installed the skill is the fallback; a bare python3 the last resort.
    Always exits 0: a prompt is never blocked.
    """
    py = python or sys.executable
    return (
        "#!/usr/bin/env bash\n"
        f"# check-comment-bus.sh — {GENERATED_MARK}; do not edit.\n"
        "# UserPromptSubmit hook shim: execs the packaged hook of the agent-annotate\n"
        "# install that generated this directory, so the skill directory holds no code.\n"
        "# Always exits 0 — never block a prompt.\n"
        "set -u\n"
        f'PKG_HOOK="{HOOK_SCRIPT}"\n'
        f'PY="{py}"\n'
        '[ -f "$PKG_HOOK" ] && exec bash "$PKG_HOOK" "$@"\n'
        '[ -x "$PY" ] && exec "$PY" -m agent_annotate.hooks.check_comment_bus "$@"\n'
        "for cmd in python3 python; do\n"
        '    if command -v "$cmd" >/dev/null 2>&1; then\n'
        '        exec "$cmd" -m agent_annotate.hooks.check_comment_bus "$@"\n'
        "    fi\n"
        "done\n"
        "exit 0\n"
    )


def planned_files(provider: str, python: str | None = None, *, skills_dir: Path | None = None) -> dict[str, tuple[str, int]]:
    """{relative path: (content, mode)} for everything install_skill writes."""
    src = (skills_dir / provider) if skills_dir else skill_source(provider)
    files: dict[str, tuple[str, int]] = {}
    files["SKILL.md"] = (render_skill_md(provider, (src / "SKILL.md").read_text(encoding="utf-8")), 0o644)
    # The references are one set, kept with the Claude skill; every provider ships them.
    refs = (skills_dir or SKILLS_DIR) / "claude" / "references"
    for ref in sorted(refs.glob("*.md")):
        files[f"references/{ref.name}"] = (ref.read_text(encoding="utf-8"), 0o644)
    for extra in sorted((src / "agents").glob("*.yaml")) if (src / "agents").is_dir() else []:
        files[f"agents/{extra.name}"] = (extra.read_text(encoding="utf-8"), 0o644)
    files["hooks/check-comment-bus.sh"] = (hook_shim(python), 0o755)
    files["hooks/session-start.sh"] = (
        f"#!/usr/bin/env bash\n# {GENERATED_MARK}; do not edit.\n"
        f"exec {shlex.quote(python or sys.executable)} -S {shlex.quote(str(SESSION_START_SCRIPT.with_name('session_start.py')))} \"$@\"\n", 0o755)
    return files


def _write_atomic(path: Path, content: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    os.chmod(tmp, mode)
    os.replace(tmp, path)


def install_skill(provider: str, dest: Path, python: str | None = None) -> list[str]:
    """Write the provider skill into `dest`. Returns one report line per file:
    'wrote', 'updated', 'mode' (content same, execute bit fixed) or 'unchanged'."""
    dest = Path(dest).expanduser().resolve()
    lines: list[str] = []
    planned = planned_files(provider, python)
    try:
        previous = json.loads((dest / ".annotate-install.json").read_text()).get("files", {})
    except (OSError, ValueError):
        previous = {}
    for rel, digest in previous.items():
        target = (dest / rel).resolve()
        if (rel not in planned and target.is_relative_to(dest) and target.is_file()
                and hashlib.sha256(target.read_bytes()).hexdigest() == digest):
            target.unlink()
            lines.append(f"removed    {rel}")
    for rel, (content, mode) in planned.items():
        target = dest / rel
        if target.is_file():
            try:
                current = target.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                current = None
            if current == content:
                if mode & 0o111 and not os.access(target, os.X_OK):
                    os.chmod(target, mode)
                    lines.append(f"mode       {rel}")
                else:
                    lines.append(f"unchanged  {rel}")
                continue
            _write_atomic(target, content, mode)
            lines.append(f"updated    {rel}")
        else:
            _write_atomic(target, content, mode)
            lines.append(f"wrote      {rel}")
    manifest = {"provider": provider, "files": {rel: hashlib.sha256(content.encode()).hexdigest()
                for rel, (content, _mode) in planned_files(provider, python).items()}}
    from . import __version__
    from .updates import build_identity
    manifest["version"] = __version__
    # The build id lets `doctor --versions` tell two builds of one version apart.
    manifest["build_id"] = build_identity()[0]
    _write_atomic(dest / ".annotate-install.json", json.dumps(manifest, indent=2), 0o644)
    registry = CONFIG_DIR / "skill-installs.json"
    try:
        installs = json.loads(registry.read_text()) if registry.exists() else {}
    except (OSError, ValueError):
        installs = {}
    installs[str(dest)] = provider
    _write_atomic(registry, json.dumps(installs, indent=2), 0o644)
    return lines


def sync_skills() -> list[str]:
    """Refresh enrolled generated deployments, preserving locally edited files."""
    registry = CONFIG_DIR / "skill-installs.json"
    if not registry.exists():
        return []
    installs = json.loads(registry.read_text())
    reports = []
    for path, provider in installs.items():
        dest = Path(path)
        try:
            manifest = json.loads((dest / ".annotate-install.json").read_text())
            conflicts = [rel for rel, digest in manifest["files"].items()
                         if not (dest / rel).is_file()
                         or hashlib.sha256((dest / rel).read_bytes()).hexdigest() != digest]
            for rel, (content, _mode) in planned_files(provider).items():
                if rel not in manifest["files"] and (dest / rel).exists():
                    if not (dest / rel).is_file() or (dest / rel).read_bytes() != content.encode():
                        conflicts.append(rel)
            if conflicts:
                reports.append(f"conflict {dest}: {', '.join(conflicts)}; deployment preserved")
                continue
            install_skill(provider, dest)
            reports.append(f"updated {dest} ({provider}); running agents must reload their skill context")
        except (OSError, ValueError, KeyError) as exc:
            reports.append(f"conflict {dest}: {exc}; deployment preserved")
    return reports


def sync_packaged_skills(root: Path) -> None:
    """Generate repository copies without enrolling or changing installed skills."""
    source = root / "src/agent_annotate/skills"
    (source / "codex/SKILL.md").write_bytes((source / "claude/SKILL.md").read_bytes())
    plugin = root / "plugins/codex/agent-annotate/skills/annotate"
    for ref in (plugin / "references").glob("*.md"):
        if not (source / "claude/references" / ref.name).exists():
            ref.unlink()
    for rel, (content, mode) in planned_files("codex", skills_dir=source).items():
        if rel.startswith("hooks/"):
            continue  # plugins use their packaged integration, not a host-specific shim
        _write_atomic(plugin / rel, content, mode)
    from .cli import command_reference
    (root / "docs/skill-commands.md").write_text(command_reference())
